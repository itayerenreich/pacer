"""Repository interfaces (Protocols).

Services depend on these, not on the SQLAlchemy classes. Any object with the
same methods fits, so service tests can pass a simple in-memory fake.
"""

from typing import Protocol

from pacer.domain import (
    ApprovalKind,
    ApprovalRequest,
    ApprovalStatus,
    Cohort,
    Goal,
    GoalUpdate,
    Group,
    PersonalFile,
    PersonalTalk,
    ProposedTask,
    StaffMeeting,
    StaffMember,
    TalkProposal,
    Task,
    Trainee,
    TraineeNote,
)


class StaffRepo(Protocol):
    def add(self, staff: StaffMember) -> StaffMember: ...
    def get(self, staff_id: int) -> StaffMember | None: ...
    def list_all(self) -> list[StaffMember]: ...


class CohortRepo(Protocol):
    def add(self, cohort: Cohort) -> Cohort: ...
    def get(self, cohort_id: int) -> Cohort | None: ...
    def list_all(self) -> list[Cohort]: ...


class GroupRepo(Protocol):
    def add(self, group: Group) -> Group: ...
    def get(self, group_id: int) -> Group | None: ...
    def list_by_cohort(self, cohort_id: int) -> list[Group]: ...


class TraineeRepo(Protocol):
    def add(self, trainee: Trainee) -> Trainee: ...
    def get(self, trainee_id: int) -> Trainee | None: ...
    def update(self, trainee: Trainee) -> Trainee: ...
    def list_all(self) -> list[Trainee]: ...
    def list_by_group(self, group_id: int) -> list[Trainee]: ...
    def list_by_counselor(self, counselor_id: int) -> list[Trainee]: ...


class PersonalFileRepo(Protocol):
    def add(self, personal_file: PersonalFile) -> PersonalFile: ...
    def get_by_trainee(self, trainee_id: int) -> PersonalFile | None: ...


class GoalRepo(Protocol):
    def add(self, goal: Goal) -> Goal: ...
    def get(self, goal_id: int) -> Goal | None: ...
    def update(self, goal: Goal) -> Goal: ...
    def list_by_trainee(self, trainee_id: int) -> list[Goal]: ...


class GoalUpdateRepo(Protocol):
    def add(self, update: GoalUpdate) -> GoalUpdate: ...
    def list_by_goal(self, goal_id: int) -> list[GoalUpdate]: ...


class ApprovalRequestRepo(Protocol):
    def add(self, request: ApprovalRequest) -> ApprovalRequest: ...
    def get(self, request_id: int) -> ApprovalRequest | None: ...
    def update(self, request: ApprovalRequest) -> ApprovalRequest: ...
    def list_pending(self, requested_by_id: int | None = None) -> list[ApprovalRequest]: ...
    def exists_with_status(
        self, *, kind: ApprovalKind, trainee_id: int, requested_by_id: int, status: ApprovalStatus
    ) -> bool: ...


class MeetingRepo(Protocol):
    def add(self, meeting: StaffMeeting) -> StaffMeeting: ...
    def get(self, meeting_id: int) -> StaffMeeting | None: ...
    def lock(self, meeting_id: int) -> StaffMeeting | None:
        """Like get(), and no other transaction can change this meeting until ours ends."""
        ...
    def update(self, meeting: StaffMeeting) -> StaffMeeting: ...
    def list_all(self) -> list[StaffMeeting]: ...


class ProposedTaskRepo(Protocol):
    def add(self, proposal: ProposedTask) -> ProposedTask: ...
    def get(self, proposal_id: int) -> ProposedTask | None: ...
    def lock(self, proposal_id: int) -> ProposedTask | None: ...
    def update(self, proposal: ProposedTask) -> ProposedTask: ...
    def list_by_meeting(self, meeting_id: int) -> list[ProposedTask]: ...
    def count_open(self, meeting_id: int) -> int: ...


class TaskRepo(Protocol):
    def add(self, task: Task) -> Task: ...
    def get(self, task_id: int) -> Task | None: ...
    def update(self, task: Task) -> Task: ...
    def list_by_owner(self, owner_id: int) -> list[Task]: ...
    def list_all(self) -> list[Task]: ...


class PersonalTalkRepo(Protocol):
    def add(self, talk: PersonalTalk) -> PersonalTalk: ...
    def get(self, talk_id: int) -> PersonalTalk | None: ...
    def lock(self, talk_id: int) -> PersonalTalk | None: ...
    def update(self, talk: PersonalTalk) -> PersonalTalk: ...
    def list_by_trainee(self, trainee_id: int) -> list[PersonalTalk]: ...


class TalkProposalRepo(Protocol):
    def add(self, proposal: TalkProposal) -> TalkProposal: ...
    def get(self, proposal_id: int) -> TalkProposal | None: ...
    def update(self, proposal: TalkProposal) -> TalkProposal: ...
    def list_by_talk(self, talk_id: int) -> list[TalkProposal]: ...
    def count_open(self, talk_id: int) -> int: ...


class TraineeNoteRepo(Protocol):
    def add(self, note: TraineeNote) -> TraineeNote: ...
    def get(self, note_id: int) -> TraineeNote | None: ...
    def delete(self, note_id: int) -> None: ...
    def list_by_trainee(self, trainee_id: int) -> list[TraineeNote]: ...
